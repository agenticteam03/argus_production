#!/usr/bin/env bash
# ACR-0018 phase 16 step 4: the private path's address allowlist on vm-095, one named entry per person with an expiry.
# The source is $DIR/allowlist.tsv (root 0600: person, address, expiry, who added it); the edge reads allow.conf
# (geo entries, generated from the unexpired rows) mounted over deploy/ui/nginx/ops-allow.conf. Addresses never go to
# Git, a record or an output pasted into one: they are personal data (#209). Every change is logged to changes.log
# without the address.
#   sudo bash ops/edge-allow.sh add <person> <IPv4 or IPv4/CIDR> [--days N] --as <lease holder>   (default 30 days)
#   sudo bash ops/edge-allow.sh remove <person> --as <lease holder>
#   sudo bash ops/edge-allow.sh list                     the people and their expiry (no address)
#   sudo bash ops/edge-allow.sh prune --scheduled        the daily timer: drop expired rows (no lease)
set -euo pipefail

HOME_DIR=${ARGUS_DEPLOY_HOME:-/opt/argus-v18}
DIR=${ARGUS_EDGE_OPS_DIR:-$HOME_DIR/edge-ops}
DOCKER=${ARGUS_DOCKER:-docker}
SRC="$DIR/allowlist.tsv"; OUT="$DIR/allow.conf"; LOG="$DIR/changes.log"
CMD=${1:-}; shift || true
PERSON=""; ADDR=""; DAYS=30; WHO=""; SCHEDULED=false

stop() { echo "EDGE ALLOW STOP: $*"; exit 1; }
while [ $# -gt 0 ]; do
  case "$1" in
    --as) shift; WHO=${1:-} ;;
    --days) shift; DAYS=${1:-} ;;
    --scheduled) SCHEDULED=true ;;
    -*) stop "unknown argument $1" ;;
    *) if [ -z "$PERSON" ]; then PERSON=$1; else ADDR=$1; fi ;;
  esac
  shift
done

need_session() {
  [ -n "$WHO" ] || stop "needs --as <lease holder>"
  grep -q "^holder=$WHO " "$HOME_DIR/SESSION" 2>/dev/null || stop "NOT YOUR SESSION"
}
person_ok() { [[ "$PERSON" =~ ^[a-z][a-z0-9_-]{1,31}$ ]] || stop "a person is a lower-case handle"; }
addr_ok() {
  [[ "$ADDR" =~ ^([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})(/([0-9]{1,2}))?$ ]] || stop "not an IPv4 address"
  for o in "${BASH_REMATCH[1]}" "${BASH_REMATCH[2]}" "${BASH_REMATCH[3]}" "${BASH_REMATCH[4]}"; do
    [ "$o" -le 255 ] || stop "not an IPv4 address"
  done
  # a /24 is the widest: a person's network, never a provider's range or everyone
  [ -z "${BASH_REMATCH[6]}" ] || [ "${BASH_REMATCH[6]}" -ge 24 ] || stop "a prefix wider than /24 is refused"
}
log() { echo "$(date -u +%Y-%m-%dT%H:%M:%SZ) $*" >> "$LOG"; }

# allow.conf from the unexpired rows, written in place (the edge's bind mount keeps the inode), then a reload
render() {
  now=$(date -u +%s)
  {
    echo "# generated by ops/edge-allow.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ); edit with it, not by hand"
    awk -F'\t' -v now="$now" '$3 > now {print $2 " 1;  # " $1}' "$SRC"
  } > "$OUT.tmp"
  cat "$OUT.tmp" > "$OUT"; rm -f "$OUT.tmp"
  chmod 0644 "$OUT"
  if "$DOCKER" ps --format '{{.Names}}' | grep -qx argus-v18-ui; then
    "$DOCKER" exec argus-v18-ui nginx -s reload >/dev/null && echo "edge reloaded"
  fi
}

mkdir -p "$DIR" && chmod 0755 "$DIR"
[ -e "$SRC" ] || { : > "$SRC"; chmod 0600 "$SRC"; }
case "$CMD" in
  add)
    need_session; person_ok; addr_ok
    [[ "$DAYS" =~ ^[1-9][0-9]*$ ]] && [ "$DAYS" -le 90 ] || stop "--days is 1 to 90"
    until=$(( $(date -u +%s) + DAYS * 86400 ))
    awk -F'\t' -v p="$PERSON" '$1 != p' "$SRC" > "$SRC.tmp"
    printf '%s\t%s\t%s\t%s\n' "$PERSON" "$ADDR" "$until" "$WHO" >> "$SRC.tmp"
    cat "$SRC.tmp" > "$SRC"; rm -f "$SRC.tmp"
    log "add $PERSON by $WHO for $DAYS days"
    render
    echo "EDGE ALLOW OK: $PERSON until $(date -u -d "@$until" +%Y-%m-%d)" ;;
  remove)
    need_session; person_ok
    awk -F'\t' -v p="$PERSON" '$1 != p' "$SRC" > "$SRC.tmp"; cat "$SRC.tmp" > "$SRC"; rm -f "$SRC.tmp"
    log "remove $PERSON by $WHO"
    render
    echo "EDGE ALLOW REMOVED: $PERSON" ;;
  list)
    now=$(date -u +%s)
    awk -F'\t' -v now="$now" '{ cmd = "date -u -d @" $3 " +%Y-%m-%d"; cmd | getline d; close(cmd);
                                print $1, ($3 > now ? "until " : "EXPIRED since ") d, "(added by " $4 ")" }' "$SRC"
    echo "EDGE ALLOW: $(awk -F'\t' -v now="$now" '$3 > now' "$SRC" | wc -l) active" ;;
  prune)
    [ "$SCHEDULED" = true ] || need_session
    now=$(date -u +%s)
    gone=$(awk -F'\t' -v now="$now" '$3 <= now {print $1}' "$SRC" | tr '\n' ' ')
    awk -F'\t' -v now="$now" '$3 > now' "$SRC" > "$SRC.tmp"; cat "$SRC.tmp" > "$SRC"; rm -f "$SRC.tmp"
    [ -z "$gone" ] || log "expired: $gone"
    render
    echo "EDGE ALLOW PRUNED: ${gone:-none}" ;;
  *) stop "usage: add <person> <address> [--days N] --as <holder> | remove <person> --as <holder> | list | prune --scheduled" ;;
esac
