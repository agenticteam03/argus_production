"""Regenerate the UI contract, then keep unchanged samples byte for byte and preserve shared IDs in --keep-new ones.

`ARGUS_UPDATE_UI_CONTRACT=1 pytest tests/test_ui_contract.py` rewrites contracts/ui-api.json and every
contracts/samples/*.json; ids and times change on each run, so the diff shows every sample. This keeps the old bytes of
each sample whose shape (keys and value types, as tests/test_ui_contract.py compares them) is the same, so the pull
request shows only the samples that really changed. A sample whose shape is the same but whose values differ beyond
ids and times (a new action, a new enum value) is reported; `--keep-new NAME` keeps its new values while restoring old
IDs referenced by another sample or a frontend test at the same JSON position. It reports every restored, already
shared, or regenerated ID kept, and rolls back if a referenced old ID has no matching new ID. It touches only
contracts/samples/ and, through the test, contracts/ui-api.json; on a failed run it puts both back. Run from the
repository root:

    python .claude/skills/ui-contract-samples/scripts/keep_unchanged_samples.py [--keep-new me.json ...]

Status 0 with a report; review `git diff contracts/` before committing.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys

SAMPLES = Path("contracts") / "samples"
CONTRACT = Path("contracts") / "ui-api.json"
# What changes on every run without meaning anything: ISO times, generated ids such as inc_8659841acddc, and sha256
# hashes (they follow other values, which are compared themselves).
TIME = re.compile(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(\.\d+)?(Z|[+-]\d\d:\d\d)?")
ID = re.compile(r"\b[a-z]{2,6}_[0-9a-f]{8,}\b")
HASH = re.compile(r"\b[0-9a-f]{64}\b")


def shape(value):
    """The same structure tests/test_ui_contract.py compares: keys and value types; a list by its first item."""
    if isinstance(value, dict):
        return {k: shape(v) for k, v in value.items()}
    if isinstance(value, list):
        return [shape(value[0])] if value else []
    return type(value).__name__


def masked(text: str) -> str:
    """The sample with its times, generated ids and hashes masked: what is left differs only for a real change."""
    return HASH.sub("<hash>", ID.sub("<id>", TIME.sub("<time>", text)))


def decide(old: dict[str, str], new: dict[str, str], keep_new=()) -> tuple[dict[str, str], list[str], list[str],
                                                                          list[str], list[str]]:
    """(the old texts to put back, the samples whose shape changed, the samples with the same shape whose other
    values differ, the new samples, the samples no longer made). A name in `keep_new` keeps its regenerated bytes."""
    keep, changed, values = {}, [], []
    for name in sorted(set(old) & set(new)):
        if shape(json.loads(old[name])) != shape(json.loads(new[name])):
            changed.append(name)
            continue
        if masked(old[name]) != masked(new[name]):
            values.append(name)
        if name not in keep_new:
            keep[name] = old[name]
    return keep, changed, values, sorted(set(new) - set(old)), sorted(set(old) - set(new))


def restore(folder: Path, keep: dict[str, str]) -> list[str]:
    """Write back the kept texts inside `folder` only; returns the names written."""
    written = []
    for name, text in sorted(keep.items()):
        if Path(name).name != name or not name.endswith(".json"):
            raise ValueError(f"not a sample name: {name!r}")
        (folder / name).write_text(text, encoding="utf-8", newline="\n")
        written.append(name)
    return written


def read(folder: Path) -> dict[str, str]:
    return {p.name: p.read_text(encoding="utf-8") for p in sorted(folder.glob("*.json"))}


def frontend_test_ids(folder: Path) -> dict[str, set[str]]:
    """IDs referenced by frontend tests, with their source paths for the report."""
    refs: dict[str, set[str]] = {}
    if not folder.is_dir():
        return refs
    for root, dirs, files in os.walk(folder):
        dirs[:] = sorted(name for name in dirs if name not in {".git", "node_modules", "dist", "build", "coverage"})
        for name in sorted(files):
            path = Path(root) / name
            relative = path.relative_to(folder).as_posix()
            parts = Path(relative).parts
            if "__tests__" not in parts and not re.search(r"(?:^|[._-])(test|spec)(?:[._-]|$)", path.name, re.I):
                continue
            source = (folder / relative).as_posix()
            for identifier in ID.findall(path.read_text(encoding="utf-8")):
                refs.setdefault(identifier, set()).add(source)
    return refs


def external_id_sources(old: dict[str, str], sample: str,
                        frontend_ids: dict[str, set[str]]) -> dict[str, set[str]]:
    """IDs referenced outside `sample` by another old sample or a frontend test."""
    refs = {identifier: set(sources) for identifier, sources in frontend_ids.items()}
    for name, text in old.items():
        if name == sample:
            continue
        for identifier in ID.findall(text):
            refs.setdefault(identifier, set()).add(name)
    return refs


def child_path(path: str, key: str) -> str:
    return f"{path}.{key}" if re.fullmatch(r"[A-Za-z_]\w*", key) else f"{path}[{json.dumps(key)}]"


def id_locations(value, path: str = "$"):
    """Yield each generated ID at its JSON path and its occurrence within a string."""
    if isinstance(value, dict):
        for key, child in value.items():
            yield from id_locations(child, child_path(path, key))
    elif isinstance(value, list):
        for index, child in enumerate(value):
            yield from id_locations(child, f"{path}[{index}]")
    elif isinstance(value, str):
        for index, match in enumerate(ID.finditer(value)):
            yield (path, index), match.group()


def reconcile_shared_ids(old_text: str, new_text: str, external: dict[str, set[str]]):
    """Restore externally referenced old IDs at matching JSON positions in a regenerated sample."""
    old_locations = dict(id_locations(json.loads(old_text)))
    new_locations = dict(id_locations(json.loads(new_text)))
    replacements: dict[tuple[str, int], str] = {}
    decisions: list[dict[str, object]] = []
    unmapped: list[dict[str, str]] = []

    for location, old_id in old_locations.items():
        new_id = new_locations.get(location)
        path = location[0]
        if old_id in external:
            if new_id is None:
                unmapped.append({"path": path, "old": old_id, "reason": "no regenerated ID at the same position"})
                continue
            if new_id != old_id:
                replacements[location] = old_id
                decisions.append({"kind": "restored", "path": path, "new": new_id, "old": old_id,
                                  "sources": sorted(external[old_id])})
            else:
                decisions.append({"kind": "already-shared", "path": path, "new": new_id, "old": old_id,
                                  "sources": sorted(external[old_id])})
        elif new_id is not None:
            kind = "kept-new" if new_id != old_id else "kept-unchanged"
            decisions.append({"kind": kind, "path": path, "new": new_id, "old": old_id, "sources": []})

    for location, new_id in new_locations.items():
        if location not in old_locations:
            if new_id in external:
                decisions.append({"kind": "already-shared", "path": location[0], "new": new_id, "old": new_id,
                                  "sources": sorted(external[new_id])})
            else:
                decisions.append({"kind": "kept-no-prior", "path": location[0], "new": new_id, "old": None,
                                  "sources": []})

    def rewrite(value, path: str = "$"):
        if isinstance(value, dict):
            return {key: rewrite(child, child_path(path, key)) for key, child in value.items()}
        if isinstance(value, list):
            return [rewrite(child, f"{path}[{index}]") for index, child in enumerate(value)]
        if isinstance(value, str):
            matches = list(ID.finditer(value))
            if not matches:
                return value
            parts = []
            end = 0
            for index, match in enumerate(matches):
                parts.extend((value[end:match.start()], replacements.get((path, index), match.group())))
                end = match.end()
            parts.append(value[end:])
            return "".join(parts)
        return value

    rewritten_data = rewrite(json.loads(new_text))
    rewritten = (json.dumps(rewritten_data, indent=2, sort_keys=True, default=str) + "\n"
                 if replacements else new_text)
    return rewritten, decisions, unmapped


def report_id_decisions(sample: str, decisions: list[dict[str, object]], unmapped: list[dict[str, str]]) -> None:
    """Report every shared ID restored, already stable, retained as new, or left unmapped."""
    groups: dict[tuple[object, ...], list[str]] = {}
    for decision in decisions:
        key = (decision["kind"], decision["new"], decision["old"], tuple(decision["sources"]))
        groups.setdefault(key, []).append(str(decision["path"]))
    if not groups and not unmapped:
        print(f"shared IDs kept or unmapped ({sample}): none")
    for (kind, new_id, old_id, sources), paths in groups.items():
        positions = ", ".join(sorted(set(paths)))
        if kind == "restored":
            print(f"kept shared ID {new_id} -> {old_id} in {sample} at {positions} (references: {', '.join(sources)})")
        elif kind == "already-shared":
            print(f"kept shared ID {new_id} in {sample} at {positions} (already matches; references: {', '.join(sources)})")
        elif kind == "kept-new":
            print(f"kept regenerated ID {new_id} in {sample} at {positions} (previous {old_id} has no external references)")
        elif kind == "kept-no-prior":
            print(f"kept regenerated ID {new_id} in {sample} at {positions} (no old ID at the same position)")
        else:
            print(f"kept unchanged ID {new_id} in {sample} at {positions} (no external references)")
    for item in unmapped:
        generated = f" -> {item['new']}" if item.get("new") else ""
        print(f"could not map shared ID {item['old']}{generated} in {sample} at {item['path']}: {item['reason']}")


def put_back(folder: Path, old: dict[str, str], contract: Path, contract_old: bytes | None) -> None:
    """After a failed run: every old sample and ui-api.json as they were, and no sample the run created."""
    restore(folder, old)
    for path in folder.glob("*.json"):
        if path.name not in old:
            path.unlink()
    if contract_old is not None:
        contract.write_bytes(contract_old)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--keep-new", action="append", default=[], metavar="NAME",
                        help="keep this sample's regenerated bytes (a reviewed value change); repeatable")
    args = parser.parse_args()
    if not (SAMPLES.is_dir() and Path("tests/test_ui_contract.py").is_file()):
        print("ERROR: run from the repository root (contracts/samples and tests/test_ui_contract.py)", file=sys.stderr)
        return 2
    old = read(SAMPLES)
    unknown = sorted(set(args.keep_new) - set(old))
    if unknown:
        print(f"ERROR: --keep-new names no existing sample: {', '.join(unknown)}", file=sys.stderr)
        return 2
    contract_old = CONTRACT.read_bytes() if CONTRACT.is_file() else None
    frontend_ids = frontend_test_ids(Path("frontend")) if args.keep_new else {}
    env = {**os.environ, "ARGUS_UPDATE_UI_CONTRACT": "1"}
    run = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "tests/test_ui_contract.py"],
                         env=env, capture_output=True, text=True, encoding="utf-8")
    if run.returncode != 0:
        print(run.stdout[-2000:], run.stderr[-2000:], sep="\n", file=sys.stderr)
        put_back(SAMPLES, old, CONTRACT, contract_old)
        print("ERROR: regenerating failed; every sample and ui-api.json put back as they were", file=sys.stderr)
        return 1
    regenerated = read(SAMPLES)
    id_reports = []
    id_errors = []
    for name in sorted(set(args.keep_new) & set(old) & set(regenerated)):
        external = external_id_sources(old, name, frontend_ids)
        rewritten, decisions, unmapped = reconcile_shared_ids(old[name], regenerated[name], external)
        id_reports.append((name, decisions, unmapped))
        if unmapped:
            id_errors.extend((name, item) for item in unmapped)
        regenerated[name] = rewritten
    for name, decisions, unmapped in id_reports:
        report_id_decisions(name, decisions, unmapped)
    if id_errors:
        put_back(SAMPLES, old, CONTRACT, contract_old)
        print("ERROR: shared IDs could not be mapped; every sample and ui-api.json put back as they were", file=sys.stderr)
        return 1
    for name in sorted(set(args.keep_new) & set(regenerated)):
        (SAMPLES / name).write_text(regenerated[name], encoding="utf-8", newline="\n")
    keep, changed, values, added, gone = decide(old, regenerated, set(args.keep_new))
    restore(SAMPLES, keep)
    print(f"kept unchanged: {len(keep)}")
    print(f"shape changed (new bytes): {', '.join(changed) or 'none'}")
    held = [n for n in values if n not in args.keep_new]
    if held:
        print(f"same shape, values differ (old kept; rerun with --keep-new NAME if the change is intended): "
              f"{', '.join(held)}")
    if args.keep_new:
        print(f"kept new bytes (--keep-new): {', '.join(sorted(args.keep_new))}")
    print(f"new samples: {', '.join(added) or 'none'}")
    if gone:
        print(f"no longer produced (left in place, delete in review if intended): {', '.join(gone)}")
    print("next: git diff contracts/  (ui-api.json is regenerated as a whole; it has no run-to-run values)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
