"""Regenerate the UI contract, then keep every sample whose shape did not change, byte for byte.

`ARGUS_UPDATE_UI_CONTRACT=1 pytest tests/test_ui_contract.py` rewrites contracts/ui-api.json and every
contracts/samples/*.json; ids and times change on each run, so the diff shows every sample. This keeps the old bytes of
each sample whose shape (keys and value types, as tests/test_ui_contract.py compares them) is the same, so the pull
request shows only the samples that really changed. A sample whose shape is the same but whose values differ beyond
ids and times (a new action, a new enum value) is reported; `--keep-new NAME` keeps its regenerated bytes. It touches
only contracts/samples/ and, through the test, contracts/ui-api.json; on a failed run it puts both back. Run from the
repository root:

    python .claude/skills/ui-contract-samples/scripts/keep_unchanged_samples.py [--keep-new me.json ...]

Status 0 with a report; review `git diff contracts/` before committing.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys

SAMPLES = Path("contracts") / "samples"
CONTRACT = Path("contracts") / "ui-api.json"
# What changes on every run without meaning anything: ISO times, generated ids such as inc_8659841acddc, and sha256
# hashes (they follow other values, which are compared themselves).
TIME = re.compile(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(\.\d+)?(Z|[+-]\d\d:\d\d)?")
ID = re.compile(r"\b[a-z]{2,6}_[0-9a-f]{8,}\b")
HASH = re.compile(r"\b[0-9a-f]{64}\b")


def shape(value):
    """The same structure tests/test_ui_contract.py compares: keys and value types; a list by its first item."""
    if isinstance(value, dict):
        return {k: shape(v) for k, v in value.items()}
    if isinstance(value, list):
        return [shape(value[0])] if value else []
    return type(value).__name__


def masked(text: str) -> str:
    """The sample with its times, generated ids and hashes masked: what is left differs only for a real change."""
    return HASH.sub("<hash>", ID.sub("<id>", TIME.sub("<time>", text)))


def decide(old: dict[str, str], new: dict[str, str], keep_new=()) -> tuple[dict[str, str], list[str], list[str],
                                                                          list[str], list[str]]:
    """(the old texts to put back, the samples whose shape changed, the samples with the same shape whose other
    values differ, the new samples, the samples no longer made). A name in `keep_new` keeps its regenerated bytes."""
    keep, changed, values = {}, [], []
    for name in sorted(set(old) & set(new)):
        if shape(json.loads(old[name])) != shape(json.loads(new[name])):
            changed.append(name)
            continue
        if masked(old[name]) != masked(new[name]):
            values.append(name)
        if name not in keep_new:
            keep[name] = old[name]
    return keep, changed, values, sorted(set(new) - set(old)), sorted(set(old) - set(new))


def restore(folder: Path, keep: dict[str, str]) -> list[str]:
    """Write back the kept texts inside `folder` only; returns the names written."""
    written = []
    for name, text in sorted(keep.items()):
        if Path(name).name != name or not name.endswith(".json"):
            raise ValueError(f"not a sample name: {name!r}")
        (folder / name).write_text(text, encoding="utf-8", newline="\n")
        written.append(name)
    return written


def read(folder: Path) -> dict[str, str]:
    return {p.name: p.read_text(encoding="utf-8") for p in sorted(folder.glob("*.json"))}


def put_back(folder: Path, old: dict[str, str], contract: Path, contract_old: bytes | None) -> None:
    """After a failed run: every old sample and ui-api.json as they were, and no sample the run created."""
    restore(folder, old)
    for path in folder.glob("*.json"):
        if path.name not in old:
            path.unlink()
    if contract_old is not None:
        contract.write_bytes(contract_old)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--keep-new", action="append", default=[], metavar="NAME",
                        help="keep this sample's regenerated bytes (a reviewed value change); repeatable")
    args = parser.parse_args()
    if not (SAMPLES.is_dir() and Path("tests/test_ui_contract.py").is_file()):
        print("ERROR: run from the repository root (contracts/samples and tests/test_ui_contract.py)", file=sys.stderr)
        return 2
    old = read(SAMPLES)
    unknown = sorted(set(args.keep_new) - set(old))
    if unknown:
        print(f"ERROR: --keep-new names no existing sample: {', '.join(unknown)}", file=sys.stderr)
        return 2
    contract_old = CONTRACT.read_bytes() if CONTRACT.is_file() else None
    env = {**os.environ, "ARGUS_UPDATE_UI_CONTRACT": "1"}
    run = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "tests/test_ui_contract.py"],
                         env=env, capture_output=True, text=True, encoding="utf-8")
    if run.returncode != 0:
        print(run.stdout[-2000:], run.stderr[-2000:], sep="\n", file=sys.stderr)
        put_back(SAMPLES, old, CONTRACT, contract_old)
        print("ERROR: regenerating failed; every sample and ui-api.json put back as they were", file=sys.stderr)
        return 1
    keep, changed, values, added, gone = decide(old, read(SAMPLES), set(args.keep_new))
    restore(SAMPLES, keep)
    print(f"kept unchanged: {len(keep)}")
    print(f"shape changed (new bytes): {', '.join(changed) or 'none'}")
    held = [n for n in values if n not in args.keep_new]
    if held:
        print(f"same shape, values differ (old kept; rerun with --keep-new NAME if the change is intended): "
              f"{', '.join(held)}")
    if args.keep_new:
        print(f"kept new bytes (--keep-new): {', '.join(sorted(args.keep_new))}")
    print(f"new samples: {', '.join(added) or 'none'}")
    if gone:
        print(f"no longer produced (left in place, delete in review if intended): {', '.join(gone)}")
    print("next: git diff contracts/  (ui-api.json is regenerated as a whole; it has no run-to-run values)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
